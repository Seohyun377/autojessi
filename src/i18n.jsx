// translate a vehicle's display fields for the given locale (raw object untouched)
function trVehicle(v, l) {
  if (l === "ko") {
    return { maker: v.maker, model: v.model, trim: v.trim, color: v.color, region: v.region,
      fuel: v.fuel, trans: v.trans, name: `${v.year} ${v.maker} ${v.model}` };
  }
  const i = (v.i18n && (v.i18n[l] || v.i18n.en)) || {};
  const maker = trMaker(v.maker, l);
  const model = i.model || trModel(v.model, l);
  return { maker, model, trim: i.trim || trModel(v.trim, l), color: i.color || v.color,
    region: trRegion(v.region, l), fuel: trFuel(v.fuel, l), trans: trTrans(v.trans, l),
    note: i.note || v.accidentNote, name: `${v.year} ${maker} ${model}` };
}

// ── locale-aware short money for bid increments ──────────────────────────────────
function fmtIncShort(v, l) {
  if (l === "ko") return window.fmtKRWShort(v);
  const m = v / 1e6;
  const s = m >= 10 ? Math.round(m).toString() : m.toFixed(1).replace(/\.0$/, "");
  return "₩" + s + "M";
}

